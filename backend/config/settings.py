def load_env_file():
    """Read simple KEY=VALUE lines from backend/.env (if the file exists).

    This is where your email password and Google client id are kept, so they
    are not written inside the code.
    """
    env_path = BASE_DIR / ".env"
    if not env_path.exists():
        return
    for line in env_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


load_env_file()



